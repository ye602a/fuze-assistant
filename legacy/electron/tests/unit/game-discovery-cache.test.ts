import { afterEach, describe, expect, it, vi } from 'vitest'
const mocks = vi.hoisted(() => ({ exec: vi.fn(), sources: vi.fn() }))
vi.mock('child_process', () => ({ execFile: mocks.exec }))
vi.mock('electron', () => ({ desktopCapturer: { getSources: mocks.sources } }))
vi.mock('../../src/main/modules/logger.ts', () => ({ default: { debug: vi.fn(), error: vi.fn() } }))
afterEach(() => { vi.resetModules(); vi.clearAllMocks(); vi.useRealTimers() })
describe.skipIf(process.platform !== 'win32')('idle game discovery', () => {
  it('coalesces callers and does not enumerate desktop windows when game process is absent', async () => {
    vi.useFakeTimers()
    mocks.exec.mockImplementation((_exe, _args, _options, callback) => callback(null, 'INFO: No tasks'))
    const { getLolGameStatus } = await import('../../src/main/screenshot.ts')
    const results = await Promise.all([getLolGameStatus(), getLolGameStatus(), getLolGameStatus()])
    expect(results.every(result => !result.isGameOpen)).toBe(true)
    expect(mocks.exec).toHaveBeenCalledOnce()
    expect(mocks.sources).not.toHaveBeenCalled()
    await vi.advanceTimersByTimeAsync(5001)
    await getLolGameStatus()
    expect(mocks.exec).toHaveBeenCalledTimes(2)
  })
  it('falls back to window discovery on a process query error', async () => {
    mocks.exec.mockImplementation((_exe, _args, _options, callback) => callback(new Error('unavailable')))
    mocks.sources.mockResolvedValue([{ name: 'League of Legends', id: 'window:1' }])
    const { getLolGameStatus } = await import('../../src/main/screenshot.ts')
    expect(await getLolGameStatus()).toMatchObject({ processRunning: null, isGameOpen: true })
  })
})
